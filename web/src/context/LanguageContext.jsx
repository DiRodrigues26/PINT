const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [idioma, setIdioma] = useState(
    () => localStorage.getItem('idioma') || 'pt'
  );

  function mudarIdioma(novoIdioma) {
    setIdioma(novoIdioma);
    localStorage.setItem('idioma', novoIdioma);
  }

  function t(chave) {
    return T[idioma]?.[chave] ?? T.pt[chave] ?? chave;
  }

  return (
    <LanguageContext.Provider value={{ idioma, mudarIdioma, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage tem de ser usado dentro de <LanguageProvider>');
  return ctx;
}
